"""Build the blog: one HTML page per post, plus the card list on blog.html.

    blog/posts/NN-<slug>.md  ->  blog/<slug>.html

Each post file starts with a short header between --- lines, then the article
in Markdown. See docs/writing-blog-posts.md for the fields and the Markdown
that is supported.

The card grid on blog.html (between the BLOG-CARDS markers) is rewritten from
the posts, newest first. Re-run make_sitemap.py afterwards so new posts are
listed for Google.

Usage:  python3 build_blog.py
"""
import datetime
