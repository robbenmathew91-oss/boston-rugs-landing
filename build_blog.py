def card(post):
    return f'''
                <a class="blog-card" href="blog/{post["slug"]}.html">
                    <div class="blog-card-img-wrapper">
                        <img src="{post["image"]}" alt="{html.escape(post["image_alt"])}" class="blog-card-img" loading="lazy">
                    </div>
                    <div class="blog-card-content">
                        <span class="blog-card-tag">{html.escape(post["category"])}</span>
                        <h2 class="blog-card-title">{html.escape(post["title"])}</h2>
                        <p class="blog-card-excerpt">{html.escape(post["description"])}</p>
                        <span class="blog-card-link">Read Article <i class="fa-solid fa-arrow-right-long"></i></span>
                    </div>
                </a>'''


# ---------------------------------------------------------------- main

def main():
    posts = [read_post(p) for p in sorted(glob.glob(os.path.join(POSTS_DIR, '*.md')))]
    posts = [p for p in posts if p.get('draft', '').lower() not in ('yes', 'true')]
    slugs = [p['slug'] for p in posts]
    dupes = {s for s in slugs if slugs.count(s) > 1}
    if dupes:
        raise SystemExit(f'Two posts share a slug: {", ".join(sorted(dupes))}')
    # Newest first; posts with the same date keep their file-number order.
    posts.sort(key=lambda p: p['date'], reverse=True)

    header, footer = site_chrome()
    wanted = {f'{p["slug"]}.html' for p in posts}
    for old in glob.glob(os.path.join(OUT_DIR, '*.html')):
        if os.path.basename(old) not in wanted:
            os.remove(old)
    for post in posts:
        others = [p for p in posts if p is not post]
        related = ([p for p in others if p['category'] == post['category']] +
                   [p for p in others if p['category'] != post['category']])[:3]
        with open(os.path.join(OUT_DIR, f'{post["slug"]}.html'), 'w', encoding='utf-8') as f:
            f.write(post_page(post, related, header, footer))

    blog_path = os.path.join(ROOT, 'blog.html')
    page = open(blog_path, encoding='utf-8').read()
    start, end = page.index(CARDS_START) + len(CARDS_START), page.index(CARDS_END)
    page = page[:start] + ''.join(card(p) for p in posts) + '\n                ' + page[end:]
    with open(blog_path, 'w', encoding='utf-8') as f:
        f.write(page)
    print(f'{len(posts)} posts built into blog/; blog.html card list updated. Now run: python3 make_sitemap.py')


if __name__ == '__main__':
    main()
