STYLES_VERSION = '1.2.0'
THEME_VERSION = '2.1'
CARDS_START = '<!-- BLOG-CARDS:START (generated by build_blog.py) -->'
CARDS_END = '<!-- BLOG-CARDS:END -->'
REQUIRED = ('title', 'description', 'date', 'category', 'image')


# ---------------------------------------------------------------- reading posts

def read_post(path):
    text = open(path, encoding='utf-8').read()
    m = re.match(r'---\n(.*?)\n---\n(.*)', text, re.S)
    if not m:
        raise SystemExit(f'{path}: missing the --- header block')
    fields = {}
    for line in m.group(1).splitlines():
        if line.strip():
            key, _, value = line.partition(':')
            fields[key.strip()] = value.strip()
    missing = [k for k in REQUIRED if not fields.get(k)]
    if missing:
        raise SystemExit(f'{path}: missing {", ".join(missing)}')
    datetime.date.fromisoformat(fields['date'])
    name = os.path.splitext(os.path.basename(path))[0]
    fields.setdefault('slug', re.sub(r'^\d+-', '', name))
    fields.setdefault('seo_title', fields['title'])
    fields.setdefault('image_alt', fields['title'])
    fields['body_md'] = m.group(2)
    return fields


# ---------------------------------------------------------------- markdown

def inline(text):
    text = html.escape(text, quote=False)
    text = re.sub(r'!\[([^\]]*)\]\(([^)\s]+)\)', lambda m: f'<img src="{site_path(m.group(2))}" alt="{m.group(1)}" loading="lazy">', text)
    text = re.sub(r'\[([^\]]+)\]\(([^)\s]+)\)', lambda m: f'<a href="{site_path(m.group(2))}">{m.group(1)}</a>', text)
    text = re.sub(r'\*\*(.+?)\*\*', r'<strong>\1</strong>', text)
    text = re.sub(r'(?<![*\w])\*(?!\s)(.+?)(?<!\s)\*(?![*\w])', r'<em>\1</em>', text)
    return text


def site_path(url):
    """Links in posts are written like the rest of the site (rug-cleaning.html, images/x.jpg);
    posts live in /blog/, so make them start at the site root."""
    if re.match(r'^(https?:|mailto:|tel:|#|/)', url):
        return url
    return '/' + url


def markdown(md):
    out, para, items, list_tag = [], [], [], None

    def flush():
        nonlocal para, items, list_tag
        if para:
            out.append(f'<p>{inline(" ".join(para))}</p>')
            para = []
        if items:
            out.append(f'<{list_tag}>' + ''.join(f'<li>{inline(i)}</li>' for i in items) + f'</{list_tag}>')
            items, list_tag = [], None

    for raw in md.splitlines():
        line = raw.strip()
        if not line:
            flush()
            continue
        heading = re.match(r'(#{2,4})\s+(.*)', line)
        bullet = re.match(r'[-*]\s+(.*)', line)
        number = re.match(r'\d+[.)]\s+(.*)', line)
        if heading:
            flush()
            level = len(heading.group(1))
            out.append(f'<h{level}>{inline(heading.group(2))}</h{level}>')
        elif bullet or number:
            tag = 'ul' if bullet else 'ol'
            if para or (list_tag and list_tag != tag):
                flush()
            list_tag = tag
            items.append((bullet or number).group(1))
        elif line.startswith('>'):
            flush()
            out.append(f'<blockquote><p>{inline(line.lstrip("> "))}</p></blockquote>')
        elif line.startswith('<'):
            flush()
            out.append(line)
        else:
            if items:
                flush()
            para.append(line)
    flush()
    return '\n'.join(out)


def faq_pairs(md):
    """Questions written as ### headings under a '## ...FAQ...' or '## Frequently Asked...' heading."""
    m = re.search(r'^##\s+[^\n]*(FAQ|Frequently Asked)[^\n]*\n(.*?)(?=^##\s|\Z)', md, re.S | re.M | re.I)
    if not m:
        return []
    pairs = re.findall(r'^###\s+(.+?)\n(.*?)(?=^###\s|\Z)', m.group(2), re.S | re.M)
    return [(q.strip(), re.sub(r'<[^>]+>', '', markdown(a)).strip()) for q, a in pairs if a.strip()]


# ---------------------------------------------------------------- page parts

def site_chrome():
    """Header and footer copied from blog.html, with links made root-relative."""
    page = open(os.path.join(ROOT, 'blog.html'), encoding='utf-8').read()
    header = re.search(r'<header class="header">.*?</header>', page, re.S).group(0)
    footer = re.search(r'<footer class="footer">.*?</footer>', page, re.S).group(0)
    fix = lambda s: re.sub(r'(href|src)="(?!https?:|#|/|mailto:|tel:)([^"]+)"', r'\1="/\2"', s)
    return fix(header), fix(footer)


def human_date(iso):
    d = datetime.date.fromisoformat(iso)
    return f'{d:%B} {d.day}, {d.year}'


def reading_minutes(md):
    return max(1, round(len(re.findall(r'\w+', md)) / 220))


